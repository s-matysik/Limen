#!/usr/bin/env python3
"""Build the legacy-rule inventory (CSV + Markdown) for the LitRev retrofit.

The rule catalogue itself is hand-extracted from the four legacy sources (that
reading is the research contribution and cannot be automated); it lives in
``eval/_inventory_rows.json``. This script is what makes it *checkable*: it

  1. cross-validates every `limen_rule_id` against the retrofitted
     architecture.yaml — a typo or a renamed rule fails the build;
  2. cross-validates `limen_kind` against the kind the spec actually declares
     for that rule id, so the K1-K11 mapping cannot drift from reality;
  3. cross-validates that every rule in the spec is claimed by at least one
     inventory row (or is listed in NON_LEGACY_RULE_IDS below);
  4. emits eval/legacy_rule_inventory.csv and eval/legacy_rule_inventory.md
     with the per-kind and per-status counts computed, never typed.

Usage:
    python eval/build_rule_inventory.py \
        --spec ../workspace/architecture.yaml \
        --rows eval/_inventory_rows.json \
        --csv eval/legacy_rule_inventory.csv \
        --md  eval/legacy_rule_inventory.md \
        --loc eval/legacy_loc.json
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import Counter
from pathlib import Path

import yaml

FIELDS = ["rule_id", "source_file", "source_lines", "semantics", "mechanism",
          "exceptions", "legacy_severity", "limen_kind", "limen_rule_id",
          "status", "retrofit_note"]

# Rules in the spec that have no legacy counterpart, carried over from the
# Tier-1 starting point or added as engine-level hygiene.
NON_LEGACY_RULE_IDS = {
    "host-into-core-baseline",   # litrev-core-backend is out of legacy reach
    "no-debug-dd",               # PHP hygiene, Tier-1
    "frontend-agents-doc-present",
    "file-size",                 # repository-wide backstop, Tier-1
}

# K-numbering used throughout the research plan, verified against
# schemas/architecture-spec-1.json and src/limen/rules/__init__.py.
KIND_NUMBER = {
    "layer-dependency": "K1", "ownership": "K2", "consumer-allowlist": "K3",
    "public-api-only": "K4", "scoped-allowlist": "K5", "forbidden-target": "K6",
    "baseline-snapshot": "K7", "pattern-ban": "K8", "structure": "K9",
    "metric-threshold": "K10", "reachability": "K11",
}


def load_spec_rules(spec_path: Path) -> dict[str, str]:
    doc = yaml.safe_load(spec_path.read_text(encoding="utf-8"))
    return {r["id"]: r["kind"] for r in doc.get("rules", [])}


def split_ids(cell: str) -> list[str]:
    """A row may map to several limen rules; '(...)' marks a non-rule target."""
    out = []
    for part in cell.split(";"):
        part = part.strip()
        if not part or part.startswith("("):
            continue
        out.append(part.split(" ")[0])
    return out


def validate(rows: list[dict], spec_rules: dict[str, str]) -> list[str]:
    errors: list[str] = []
    claimed: set[str] = set()
    for row in rows:
        for rid in split_ids(row["limen_rule_id"]):
            if rid not in spec_rules:
                errors.append(f"{row['rule_id']}: limen rule {rid!r} "
                              f"is not in the spec")
                continue
            claimed.add(rid)
            declared_kind = row["limen_kind"]
            if declared_kind.startswith("("):
                continue
            expected = f"{KIND_NUMBER[spec_rules[rid]]} {spec_rules[rid]}"
            if declared_kind != expected:
                errors.append(f"{row['rule_id']}: claims {declared_kind!r} for "
                              f"{rid}, spec says {expected!r}")
        if row["status"] not in {"encoded", "partial", "subsumed", "not-encoded"}:
            errors.append(f"{row['rule_id']}: unknown status {row['status']!r}")
    for rid in sorted(set(spec_rules) - claimed - NON_LEGACY_RULE_IDS):
        errors.append(f"spec rule {rid!r} is not claimed by any inventory row")
    return errors


def write_csv(rows: list[dict], out: Path) -> None:
    with out.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows)


def md_escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def write_md(rows: list[dict], spec_rules: dict[str, str], loc: dict,
             spec_path: Path, out: Path) -> dict:
    by_status = Counter(r["status"] for r in rows)
    by_source = Counter(r["source_file"] for r in rows)
    kinds_in_spec = Counter(spec_rules.values())

    legacy_kind_counts: Counter = Counter(r["limen_kind"] for r in rows)

    lines: list[str] = []
    A = lines.append
    A("# Legacy rule inventory — LitRev architecture checkers → limen")
    A("")
    A("Generated by `eval/build_rule_inventory.py`; do not edit by hand.")
    A("Machine-readable form: `eval/legacy_rule_inventory.csv`. Deviations that")
    A("could not be expressed in limen: `docs/deviations.md`.")
    A("")
    A("## What was counted")
    A("")
    A(f"- **{len(rows)} legacy rules** extracted from 4 source groups "
      f"({loc['totals']['files']} files).")
    A(f"- **{len(spec_rules)} limen rules** in `{spec_path.name}`, of which "
      f"{len(spec_rules) - len(NON_LEGACY_RULE_IDS)} carry a legacy counterpart "
      f"and {len(NON_LEGACY_RULE_IDS)} have none "
      f"({', '.join(sorted(NON_LEGACY_RULE_IDS))}).")
    A("")
    A("The rule count is not the LOC ratio: several legacy entries collapse into")
    A("one limen rule (identical prefix + allowlist across paths), and several")
    A("legacy tests are pure drivers over a config array.")
    A("")
    A("## Legacy LOC per source")
    A("")
    A("`total` is `wc -l`; `code` excludes blank and comment-only lines.")
    A("")
    A("| Source group | Files | total | code | non-blank |")
    A("| --- | ---: | ---: | ---: | ---: |")
    for group in sorted(loc["per_group"]):
        g = loc["per_group"][group]
        A(f"| `{group}` | {g['files']} | {g['total_lines']} | "
          f"{g['code_lines']} | {g['non_blank_lines']} |")
    t = loc["totals"]
    A(f"| **TOTAL** | **{t['files']}** | **{t['total_lines']}** | "
      f"**{t['code_lines']}** | **{t['non_blank_lines']}** |")
    A("")
    A(f"The research plan quotes **1251 LOC**. Recomputed: "
      f"**{t['total_lines']} physical lines** "
      f"({loc['delta_vs_plan_total_lines']:+d} vs the plan) and "
      f"**{t['code_lines']} code lines** "
      f"({loc['delta_vs_plan_code_lines']:+d}). The plan's figure is within 5")
    A("lines of the *code-line* count, so it almost certainly came from a")
    A("comment-stripping counter; the `wc -l` figure is 1497. Report whichever")
    A("definition the paper uses, but state it.")
    A("")
    A("## Coverage")
    A("")
    A("| Status | Count | Meaning |")
    A("| --- | ---: | --- |")
    A(f"| `encoded` | {by_status['encoded']} | reproduced in the limen spec |")
    A(f"| `partial` | {by_status['partial']} | reproduced with a stated semantic gap "
      "(see `docs/deviations.md`) |")
    A(f"| `subsumed` | {by_status['subsumed']} | covered by another limen rule or by "
      "`limen spec validate`, not by a rule of its own |")
    A(f"| `not-encoded` | {by_status['not-encoded']} | limen cannot express it; "
      "recorded as an engine gap |")
    A("")
    A("Rules per source file:")
    A("")
    A("| Source | Legacy rules |")
    A("| --- | ---: |")
    for src in sorted(by_source):
        A(f"| `{src}` | {by_source[src]} |")
    A("")
    A("## Mapping onto limen rule kinds")
    A("")
    A("Kind numbering verified against `schemas/architecture-spec-1.json`")
    A("(the `kind` enum) and `src/limen/rules/__init__.py` (the `DISPATCH`")
    A("table); both list the same eleven kinds in the same order.")
    A("")
    A("| Kind | Legacy rules mapped | Rules in spec |")
    A("| --- | ---: | ---: |")
    for kind in sorted(kinds_in_spec, key=lambda k: int(KIND_NUMBER[k][1:])):
        label = f"{KIND_NUMBER[kind]} `{kind}`"
        A(f"| {label} | {legacy_kind_counts.get(f'{KIND_NUMBER[kind]} {kind}', 0)} "
          f"| {kinds_in_spec[kind]} |")
    A(f"| K11 `reachability` | 0 | 0 |")
    A(f"| — (no kind can express it) | {legacy_kind_counts.get('(none)', 0)} | 0 |")
    other = sum(v for k, v in legacy_kind_counts.items()
                if k.startswith("(") and k != "(none)")
    A(f"| — (spec structure, not a rule) | {other} | — |")
    A("")
    A("`K11 reachability` is unused: no legacy checker asks a transitive")
    A("question — every one of them is a direct-import or a filesystem")
    A("assertion.")
    A("")
    A("## Full inventory")
    A("")
    A("| ID | Source | Lines | Severity | limen kind | limen rule | Status |")
    A("| --- | --- | --- | --- | --- | --- | --- |")
    for r in rows:
        A(f"| `{r['rule_id']}` | `{r['source_file']}` | {r['source_lines']} "
          f"| {r['legacy_severity']} | {md_escape(r['limen_kind'])} "
          f"| {md_escape(r['limen_rule_id'])} | {r['status']} |")
    A("")
    A("### Semantics, mechanism and exceptions")
    A("")
    for r in rows:
        A(f"#### {r['rule_id']} — `{r['source_file']}:{r['source_lines']}`")
        A("")
        A(f"- **Checks:** {r['semantics']}")
        A(f"- **Mechanism:** {r['mechanism']}")
        A(f"- **Exceptions:** {r['exceptions']}")
        A(f"- **Severity (legacy):** {r['legacy_severity']}")
        A(f"- **limen:** {r['limen_kind']} → `{r['limen_rule_id']}` "
          f"({r['status']})")
        if r["retrofit_note"]:
            A(f"- **Note:** {r['retrofit_note']}")
        A("")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"by_status": dict(by_status), "by_source": dict(by_source),
            "kinds_in_spec": dict(kinds_in_spec)}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", required=True)
    ap.add_argument("--rows", default="eval/_inventory_rows.json")
    ap.add_argument("--csv", default="eval/legacy_rule_inventory.csv")
    ap.add_argument("--md", default="eval/legacy_rule_inventory.md")
    ap.add_argument("--loc", default="eval/legacy_loc.json")
    args = ap.parse_args()

    spec_path = Path(args.spec)
    rows = json.loads(Path(args.rows).read_text(encoding="utf-8"))
    spec_rules = load_spec_rules(spec_path)
    loc = json.loads(Path(args.loc).read_text(encoding="utf-8"))

    errors = validate(rows, spec_rules)
    if errors:
        for e in errors:
            print(f"inventory error: {e}", file=sys.stderr)
        return 1

    write_csv(rows, Path(args.csv))
    stats = write_md(rows, spec_rules, loc, spec_path, Path(args.md))
    print(f"legacy rules: {len(rows)} | limen rules: {len(spec_rules)}")
    print(f"status: {stats['by_status']}")
    print(f"rules per kind in spec: {stats['kinds_in_spec']}")
    print(f"wrote {args.csv} and {args.md}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
